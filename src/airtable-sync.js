// ── Main sync function ────────────────────────────────────────────────────────

/**
 * Sync Chartex data to Airtable.
 *
 * @param {Array}  ebrilSnapshots   — from ChartexClient.getEbrilSnapshot()
 * @param {Array}  risingSounds     — from ChartexClient.getRisingSounds()
 * @param {Array}  risingCreators   — from ChartexClient.getRisingCreators()
 */
async function syncToAirtable(ebrilSnapshots, risingSounds, risingCreators) {
  const runDate = new Date().toISOString().split('T')[0];
  const log = (msg) => console.log(`[airtable-sync] ${msg}`);

  // 1. Create monitoring campaign
  log('Creating monitoring campaign…');
  const [campaignResult] = await createRecords(TABLES.campaigns, [
    buildMonitoringCampaign(runDate, ebrilSnapshots.length),
  ]);
  log(`Campaign created: ${campaignResult.records[0].id}`);

  // 2. Upsert creators who are using Ebril's sounds → People
  log('Syncing creators using Ebril sounds…');
  const creatorPersonMap = {};  // username → airtable record id

  for (const snapshot of ebrilSnapshots) {
    if (!snapshot.creators.length) continue;
    const personRecords = snapshot.creators.map((c) =>
      buildCreatorPerson(c, snapshot.track.title)
    );
    const results = await createRecords(TABLES.people, personRecords);
    results.forEach((res) => {
      res.records.forEach((rec, i) => {
        const username = snapshot.creators[i]?.username;
        if (username) creatorPersonMap[username] = rec.id;
      });
    });
  }
  log(`Synced ${Object.keys(creatorPersonMap).length} creator people records.`);

  // 3. Create usage moment for each Ebril track
  log('Creating song usage moments…');
  for (const snapshot of ebrilSnapshots) {
    const creatorIds = snapshot.creators
      .map((c) => creatorPersonMap[c.username])
      .filter(Boolean);
    await createRecords(TABLES.moments, [
      buildUsageMoment(snapshot.track, snapshot.usage, creatorIds),
    ]);
  }
  log(`Created ${ebrilSnapshots.length} usage moment(s).`);

  // 4. Add rising sounds as discovery alerts
  log('Creating rising sound alert moments…');
  if (risingSounds.length) {
    await createRecords(
      TABLES.moments,
      risingSounds.map(buildRisingSoundMoment)
    );
  }
  log(`Created ${risingSounds.length} rising sound alert(s).`);

  // 5. Add rising creators to People
  log('Syncing rising creators…');
  if (risingCreators.length) {
    await createRecords(
      TABLES.people,
      risingCreators.map(buildRisingCreatorPerson)
    );
  }
  log(`Synced ${risingCreators.length} rising creator(s).`);

  log('Sync complete.');
  return {
    campaign: campaignResult.records[0].id,
    creatorsSynced: Object.keys(creatorPersonMap).length,
    usageMoments: ebrilSnapshots.length,
    risingSoundAlerts: risingSounds.length,
    risingCreatorsSynced: risingCreators.length,
  };
}

