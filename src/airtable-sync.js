// ── HTTP helper ───────────────────────────────────────────────────────────────

function atRequest(method, path, body) {
  return new Promise((resolve, reject) => {
    const url = `${AT_BASE}/${BASE_ID}/${path}`;
    const payload = body ? JSON.stringify(body) : null;
    const parsed = new URL(url);

    const options = {
      hostname: parsed.hostname,
      path: parsed.pathname + parsed.search,
      method,
      headers: {
        Authorization: `Bearer ${API_KEY}`,
        'Content-Type': 'application/json',
        ...(payload ? { 'Content-Length': Buffer.byteLength(payload) } : {}),
      },
    };

    const req = https.request(options, (res) => {
      let data = '';
      res.on('data', (c) => (data += c));
      res.on('end', () => {
        if (res.statusCode >= 400) {
          return reject(new Error(`Airtable ${res.statusCode}: ${data}`));
        }
        try { resolve(JSON.parse(data)); }
        catch (e) { reject(new Error(`Parse error: ${data}`)); }
      });
    });

    req.on('error', reject);
    if (payload) req.write(payload);
    req.end();
  });
}

function createRecords(tableId, records) {
  // Airtable accepts max 10 records per request
  const chunks = [];
  for (let i = 0; i < records.length; i += 10) chunks.push(records.slice(i, i + 10));
  return Promise.all(chunks.map((chunk) => atRequest('POST', tableId, { records: chunk })));
}

